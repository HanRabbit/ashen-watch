// Bake only the three licensed motion performances; source zip, mannequin, skin,
// textures and foreign bone axes are not runtime dependencies. See characters/CREDITS.md.
// node tools/bake-watchman-motion.mjs /path/to/AnimationLibrary_Godot_Standard.glb
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { Object3D, Vector3, VectorKeyframeTrack, QuaternionKeyframeTrack } from 'three';
const bytes=readFileSync(process.argv[2]);
if(createHash('sha256').update(bytes).digest('hex')!=='1b7bf67866360665426bb99e4c71bd619f19b408453c24e30f0c3071601eee5c')throw Error('Unexpected reference file; recheck phase and axes before rebaking');
const jsonEnd=20+bytes.readUInt32LE(12), doc=JSON.parse(bytes.subarray(20,jsonEnd).toString()), bin=jsonEnd+8;
const fields={hips:'hips',head:'head',neck:'neck'};
for(const side of ['L','R'])for(const [name,source] of Object.entries({arm:'upper_arm',foreArm:'forearm',hand:'hand',upLeg:'thigh',leg:'shin',foot:'foot',toe:'toe'})) fields[name+side]=source+'.'+side;
const channels=Object.keys(fields),frames=64;
function read(index){const a=doc.accessors[index],v=doc.bufferViews[a.bufferView];
  if(a.componentType!==5126||a.sparse||v.byteStride)throw Error('Unsupported source accessor');
  return new Float32Array(bytes.buffer,bytes.byteOffset+bin+(v.byteOffset??0)+(a.byteOffset??0),a.count*({SCALAR:1,VEC3:3,VEC4:4}[a.type]));}
function extract(name){
  const nodes=doc.nodes.map(n=>{const o=new Object3D();o.name=n.name;if(n.rotation)o.quaternion.fromArray(n.rotation);if(n.translation)o.position.fromArray(n.translation);if(n.scale)o.scale.fromArray(n.scale);return o;});
  doc.nodes.forEach((n,i)=>n.children?.forEach(c=>nodes[i].add(nodes[c])));
  const root=nodes[doc.scenes[0].nodes[0]],js=Object.fromEntries(Object.entries(fields).map(([k,v])=>[k,root.getObjectByName('DEF-'+v)]));
  const x=js.upLegR.getWorldPosition(new Vector3()).sub(js.upLegL.getWorldPosition(new Vector3())); x.y=0;x.normalize();
  const toe=js.toeL.getWorldPosition(new Vector3()).sub(js.footL.getWorldPosition(new Vector3()));
  const z=new Vector3(-x.z,0,x.x);if(z.dot(toe)<0)z.negate();
  const a=doc.animations.find(c=>c.name===name);let duration=0;
  const curves=a.channels.map(c=>{const s=a.samplers[c.sampler],t=read(s.input),values=read(s.output),joint=nodes[c.target.node];
    if(s.interpolation!=='LINEAR')throw Error('Unsupported interpolation');duration=Math.max(duration,t.at(-1));
    const prop={rotation:'quaternion',translation:'position',scale:'scale'}[c.target.path];
    const Key=prop==='quaternion'?QuaternionKeyframeTrack:VectorKeyframeTrack;
    const interpolant=new Key(prop,t,values).createInterpolant();return seconds=>joint[prop].fromArray(interpolant.evaluate(seconds));});
  const tmp=new Vector3();
  const at=phase=>{curves.forEach(f=>f(duration*((phase%1+1)%1)));root.updateMatrixWorld(true);
    return Object.fromEntries(channels.map(k=>{js[k].getWorldPosition(tmp);return [k,[x.dot(tmp),tmp.y,z.dot(tmp)]];}));};
  if(process.env.AW_MOTION_INSPECT){console.log(name,'duration',duration,'axes',x.toArray(),z.toArray());for(let i=0;i<32;i++){const {footL,footR,toeL,hips}=at(i/32); console.log(i/32,...[footL[2],footL[1],toeL[1],footR[2],footR[1],hips[1]].map(v=>v.toFixed(3)));}}
  return {at,duration};
}
// Align transitions at lead-foot touchdown (jog contacts one 30-Hz key later).
const clips={Walk_Loop:0,Jog_Fwd_Loop:1/28,Sprint_Loop:0};
const raw=Object.entries(clips).map(([name,offset])=>{const {at,duration}=extract(name);const poses=Array.from({length:frames},(_,i)=>at(i/frames+offset));
  const centre=[0,0,0];for(const p of poses)for(const k of [0,2])centre[k]+=(p.upLegL[k]+p.upLegR[k])/(2*frames);
  const samples=poses.flatMap(p=>channels.flatMap(k=>p[k].map((v,i)=>Math.round((v-centre[i])*1000))));
  return {name,duration,samples};});
if(!process.env.AW_MOTION_INSPECT){
  const source='// Generated by tools/bake-watchman-motion.mjs. Quaternius UAL (CC0). Positions in millimetres.\n'+
    `export const motionJoints=${JSON.stringify(channels)} as const;\nexport const motionFrames=${frames};\n`+
    raw.map(({name,duration,samples})=>`// ${name}, original loop ${duration.toFixed(3)} s.\n`).join('')+
    'export const motionClips=[\n'+raw.map(({samples})=>'  new Int16Array([\n'+Array.from({length:frames},(_,i)=>'    '+samples.slice(i*channels.length*3,(i+1)*channels.length*3).join(',')+',').join('\n')+'\n  ])').join(',\n')+'\n] as const;\n';
  writeFileSync(new URL('../src/render/baked/watchmanMotionData.ts',import.meta.url),source);
}
